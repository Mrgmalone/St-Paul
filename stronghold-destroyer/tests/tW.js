const { chromium } = require('playwright'); const fs = require('fs'); const SP = require('./env').SP;
(async () => { const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
  await p.route('**/three.min.js', r => r.abort());
  const errs = []; p.on('pageerror', e => errs.push(e.message + ' | ' + (e.stack||'').split('\n')[1]));
  await p.goto(require('./env').GAME); await p.waitForTimeout(800);
  await p.click('.civ[data-civ="harvest"]'); await p.waitForTimeout(500);
  await p.evaluate(()=>{ SD.setRaid(9999); document.getElementById('banner').style.opacity = 1; });
  const ban = () => p.evaluate(()=>document.getElementById('banner').textContent);
  const W = () => p.evaluate(()=>`sword=${SD.res.sword} spear=${SD.res.spear} bow=${SD.res.bow} gold=${Math.floor(SD.res.gold)} queue=${SD.trainQueue.map(q=>q.kind).join(',')}`);
  console.log('start:', await W());
  await p.click('.tab[data-tab="army"]'); await p.waitForTimeout(200);
  console.log('info:', await p.textContent('#armoryInfo'));
  await p.evaluate(()=>{ SD.res.gold = 0; }); await p.waitForTimeout(300);
  await p.click('.tb[data-k="spear"]', { force: true }); console.log('spear, 0 gold ->', await ban(), '|', await W());
  await p.click('.tb[data-k="sword"]', { force: true }); console.log('sword, no sword ->', await ban());
  await p.evaluate(()=>{ SD.res.gold = 100; SD.res.food = 500; SD.res.wood = 500; }); await p.waitForTimeout(300);
  await p.click('.tb[data-k="sword"]', { force: true }); console.log('sword w/ food+wood but no sword ->', await ban(), '|', await W());
  await p.click('.tb[data-k="spear"]'); console.log('spear w/ spear ->', await W());
  await p.click('.wb[data-w="sword"]', { force: true }); console.log('buy w/o armory ->', await ban(), '|', await W());
  console.log('buy buttons off?', await p.evaluate(()=>[...document.querySelectorAll('.wb')].map(b=>b.classList.contains('off')).join(',')));
  // smithy with no armory: worker waits
  await p.evaluate(()=>{ const mk=(k,c,r)=>{ const b=SD.createBuilding(k,c,r); b.progress=1; b.done=true; b.hp=b.maxHp; return b; }; mk('smithy', 8, 22);
    const k = SD.keep(); for (let i = 0; i < 2; i++) makeUnit('player', 'civ', k.x1 + 30 + i * 12, k.y1 + 30); SD.res.iron = 10; });
  await p.waitForTimeout(25000);
  console.log('smithy no armory:', await W(), JSON.stringify(await p.evaluate(()=>SD.units.filter(u=>u.job&&u.job.kind==='smithy').map(u=>u.order+'/'+u.sub+' carry '+u.carry+' '+u.carryType))));
  await p.evaluate(()=>{ const b=SD.createBuilding('armory', 11, 22); b.progress=1; b.done=true; b.hp=b.maxHp; }); await p.waitForTimeout(15000);
  console.log('after armory built:', await W());
  await p.evaluate(()=>{ SD.res.gold = 100; }); await p.waitForTimeout(300);
  console.log('info:', await p.textContent('#armoryInfo'));
  await p.click('.wb[data-w="sword"]'); await p.click('.wb[data-w="bow"]'); console.log('bought sword+bow:', await W());
  await p.click('.tb[data-k="sword"]'); await p.click('.tb[data-k="archer"]'); console.log('trained:', await W());
  await p.screenshot({ path: SP + '/W_army.png' });
  console.log('errors', errs.slice(0, 5)); await b.close(); })();
